    private boolean validaFormCadastro() {
        if (txtUsuarioCadastro.getText().equals("")) {
            JOptionPane.showMessageDialog(this,
                    "Preencha o campo Usuário!",
                    this.getTitle(),
                    JOptionPane.ERROR_MESSAGE);
            txtUsuarioCadastro.requestFocus();
            return false;
        }

        if (String.valueOf(passwordFieldSenhaCadastro.getPassword()).equals("")) {
            JOptionPane.showMessageDialog(this,
                    "Preencha o campo Senha!",
                    this.getTitle(),
                    JOptionPane.ERROR_MESSAGE);
            passwordFieldSenhaCadastro.requestFocus();
            return false;
        }

        return true;
    }
    
    private boolean verificarHistoricoSenhas(String senha){
        HistoricoDAO senhaDao = new HistoricoDAO();
        listaHistoricos = senhaDao.lista();
        
        for (Historico historico : listaHistoricos) {
            if(historico.getSenhaAntiga().equals(senha)){
                JOptionPane.showMessageDialog(null, "A senha não pode ser igual às anteriores!");
                passwordFieldSenhaCadastro.requestFocus();
                return false;
            }  
        }
        return true;
    }
    
    private boolean compararSenhasAtivas(String senha){
        UsuarioDAO usuarioDao = new UsuarioDAO();
        listaUsuarios = usuarioDao.lista();
        
        for (Usuario usuario : listaUsuarios) {
            if(usuario.getSenhaUsuario().equals(senha)){
                JOptionPane.showMessageDialog(this,
                "A senha digitada já está cadastrada para outro usuário!",
                this.getTitle(),
                JOptionPane.ERROR_MESSAGE);
                passwordFieldSenhaCadastro.requestFocus();
                return false;
            }
            
        }
        return true;
    }
                  
    private boolean validarSenha(char[] senhaArray) {
        String senha = new String(senhaArray);

        // Expressão regular que cobre todos os requisitos
        String regex = "^(?=.*[a-z])(?=.*[A-Z])(?=.*\\d)(?=.*[!@#\\$%\\^&\\*\\(\\)_\\+\\-=\\[\\]{};':\"\\\\|,.<>/?]).{8,}$";

        return senha.matches(regex);
    }

