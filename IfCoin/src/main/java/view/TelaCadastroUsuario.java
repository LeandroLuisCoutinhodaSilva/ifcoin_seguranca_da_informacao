    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        //Criando uma sequência de caracteres para poder testar se a senha atende aos requisitos
        char [] senha = passwordFieldSenhaCadastro.getPassword();
        boolean inserido;
        Usuario user = new Usuario();
        UsuarioDAO usuarioDao = new UsuarioDAO();
        
        //Criando um novo histórico para salvar no banco. Dessa forma, toda vez que uma senha é criada, ela vira um histórico, seja ativa
        // ou antiga, para
        //não ser possível outro usuário criar uma senha igual
        Historico hist = new Historico();
        HistoricoDAO histDao = new HistoricoDAO();
        
        //Testes para verificar se a senha atende aos requisitos
        if(validaFormCadastro() && validarSenha(senha) && verificarHistoricoSenhas(String.valueOf(senha)) 
                && compararSenhasAtivas(String.valueOf(senha))){
            
            String nomeUsuario = txtUsuarioCadastro.getText();
            String senhaUsuario = String.valueOf(passwordFieldSenhaCadastro.getPassword());
            
            user.setNomeUsuario(nomeUsuario);
            user.setSenhaUsuario(senhaUsuario);
            
            inserido = usuarioDao.insert(user);
            
            //Para testar se o usuário foi realmente inserido no banco. Se ele foi inserido, a sua senha deve ser armazenada na lista das
            //últimas 7 senhas
            if (inserido) {
                JOptionPane.showMessageDialog(null, "Usuário inserido com sucesso!");
                
                hist.setIdUsuario(user.getIdUsuario());//Esse id do usuário é o que veio do banco no ResultSetGet_tGenerated_Keys)
                hist.setSenhaAntiga(user.getSenhaUsuario());
                
                if(listaHistoricos.size() < 7){
                    histDao.insert(hist);
                }else{
                    Historico historicoSenha = listaHistoricos.get(0);//Pega a primeira senha da lista de senhas do histórico 
                    histDao.excluir(historicoSenha.getIdHistorico()); //Remove a primeira senha da lista(a mais antiga)
                    System.out.println(hist);
                    histDao.insert(hist);//Insere o novo histórico na lista                                    
                }
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao cadastrar usuário!", this.getTitle(), JOptionPane.ERROR_MESSAGE);
            }
        } else if(!validarSenha(senha)){
            JOptionPane.showMessageDialog(null,
        "A senha deve conter no mínimo 8 caracteres,\ncom pelo menos uma letra maiúscula, uma minúscula,\num número e um caractere especial.");
        }    
    }//GEN-LAST:event_btnCadastrarActionPerformed

