    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        //Criando uma sequência de caracteres para poder testar se a senha atende aos requisitos
        char [] senha = passwordFieldNovaSenha.getPassword();
        boolean atualizado;
        UsuarioDAO usuarioDao = new UsuarioDAO();
        
        //Criando um novo histórico para salvar no banco. Dessa forma, toda vez que uma senha é criada, ela vira um histórico, seja ativa
        // ou antiga, para
        //não ser possível outro usuário criar uma senha igual
        Historico hist = new Historico();
        HistoricoDAO histDao = new HistoricoDAO();
        
        //Testes para verificar se a senha atende aos requisitos
        if(validaFormAtualizacao() && validarSenhaAtualizacao(senha) && verificarHistoricoSenhasAtualizacao(String.valueOf(senha)) 
                && compararSenhasAtivasAtualizacao(String.valueOf(senha))){
            
            java.util.Date dataUltimaSenha = new java.util.Date();
            
            usuario.setSenhaUsuario(String.valueOf(senha));
            usuario.setDataUltimaTroca(dataUltimaSenha);
            
            atualizado = usuarioDao.update(usuario);
            
            //Para testar se o usuário foi realmente inserido no banco. Se ele foi inserido, a sua senha deve ser armazenada na lista das
            //últimas 7 senhas
            if (atualizado) {
                JOptionPane.showMessageDialog(null, "Senha atualizada com sucesso!");
                
                hist.setIdUsuario(usuario.getIdUsuario());//Esse id do usuário é o id do usuário que está atualizando a senha
                hist.setSenhaAntiga(usuario.getSenhaUsuario());
                
                if(listaHistoricos.size() < 7){
                    histDao.insert(hist);
                }else{
                    Historico historicoSenha = listaHistoricos.get(0);//Pega a primeira senha da lista de senhas do histórico 
                    histDao.excluir(historicoSenha.getIdHistorico()); //Remove a primeira senha da lista(a mais antiga)
                    System.out.println(hist);
                    histDao.insert(hist);//Insere o novo histórico na lista                                    
                }
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao atualizar a senha!", this.getTitle(), JOptionPane.ERROR_MESSAGE);
            }
        } else if(!validarSenhaAtualizacao(senha)){
            JOptionPane.showMessageDialog(null,
        "A senha deve conter no mínimo 8 caracteres,\ncom pelo menos uma letra maiúscula, uma minúscula,\num número e um caractere especial.");
        }    
    }//GEN-LAST:event_btnAtualizarActionPerformed

