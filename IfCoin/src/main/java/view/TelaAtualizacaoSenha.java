    private void setarCampos(){
        passwordFielSenhaAtual.setText(usuario.getSenhaUsuario());
    }
    
    private boolean validaFormAtualizacao() {
        if (String.valueOf(passwordFieldNovaSenha.getPassword()).equals("")) {
            JOptionPane.showMessageDialog(this,
                    "Preencha o campo da nova Senha!",
                    this.getTitle(),
                    JOptionPane.ERROR_MESSAGE);
            passwordFieldNovaSenha.requestFocus();
            return false;
        }
        return true;
    }
    
    private boolean verificarHistoricoSenhasAtualizacao(String senha){
        HistoricoDAO senhaDao = new HistoricoDAO();
        listaHistoricos = senhaDao.lista();
        
        for (Historico historico : listaHistoricos) {
            if(historico.getSenhaAntiga().equals(senha)){
                JOptionPane.showMessageDialog(null, "A senha não pode ser igual às anteriores!");
                passwordFieldNovaSenha.requestFocus();
                return false;
            }  
        }
        return true;
    }
    
    private boolean compararSenhasAtivasAtualizacao(String senha){
        UsuarioDAO usuarioDao = new UsuarioDAO();
        listaUsuarios = usuarioDao.lista();
        
        for (Usuario usr : listaUsuarios) {
            if(usr.getSenhaUsuario().equals(senha)){
                JOptionPane.showMessageDialog(this,
                "A senha digitada já está cadastrada para outro usuário!",
                this.getTitle(),
                JOptionPane.ERROR_MESSAGE);
                passwordFieldNovaSenha.requestFocus();
                return false;
            }
            
        }
        return true;
    }
                  
    private boolean validarSenhaAtualizacao(char[] senhaArray) {
        String senha = new String(senhaArray);

        // Expressão regular que cobre todos os requisitos
        String regex = "^(?=.*[a-z])(?=.*[A-Z])(?=.*\\d)(?=.*[!@#\\$%\\^&\\*\\(\\)_\\+\\-=\\[\\]{};':\"\\\\|,.<>/?]).{8,}$";

        return senha.matches(regex);
    }

